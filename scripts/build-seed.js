// Generates worker/seed.sql from src/data/seedRecipes.js using the same classifier and calorie
// estimator as the app. Run: node scripts/build-seed.js   (then apply with `npm run d1:seed`).
const fs = require('fs');
const path = require('path');
const seedRecipes = require('../src/data/seedRecipes');
const { classifyIngredients, estimateCalories } = require('../src/services/diet');
const { parseMeasure } = require('../src/services/grocery');

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const now = new Date().toISOString();
const out = ['-- Generated by scripts/build-seed.js. Safe to re-run: existing recipes are skipped.'];

for (const dto of seedRecipes) {
  const diet = classifyIngredients(dto.ingredients.map((i) => i.name));
  let calories = estimateCalories(dto.ingredients, dto.servings || 4);
  if (calories !== null && calories > 1400) calories = null;
  const src = q(dto.source);
  const ext = q(dto.externalId);
  out.push(`INSERT OR IGNORE INTO recipes (source, externalId, title, category, area, summary, instructions, thumb, youtube, calories, caloriesSource, isVegetarian, isVegan, isGlutenFree, tags, createdAt, updatedAt) VALUES (${[
    src, ext, q(dto.title), q(dto.category), q(dto.area), q(dto.summary), q(dto.instructions), 'NULL', 'NULL',
    q(calories), q(calories !== null ? 'estimate' : null), diet.isVegetarian ? 1 : 0, diet.isVegan ? 1 : 0, diet.isGlutenFree ? 1 : 0,
    q(JSON.stringify(dto.tags || [])), q(now), q(now)].join(', ')});`);
  const ings = dto.ingredients.map((i) => {
    const p = parseMeasure(i.measure);
    return { name: i.name, measure: i.measure || null, quantity: p.quantity, unit: p.unit };
  });
  // changes() is 0 when the recipe already existed, so re-running never duplicates ingredients.
  out.push(`INSERT INTO ingredients (name, measure, quantity, unit, RecipeId, createdAt, updatedAt) SELECT json_extract(j.value,'$.name'), json_extract(j.value,'$.measure'), json_extract(j.value,'$.quantity'), json_extract(j.value,'$.unit'), r.id, ${q(now)}, ${q(now)} FROM json_each(${q(JSON.stringify(ings))}) j, (SELECT id FROM recipes WHERE source = ${src} AND externalId = ${ext}) r WHERE changes() > 0;`);
}
fs.writeFileSync(path.join(__dirname, '..', 'worker', 'seed.sql'), `${out.join('\n')}\n`);
console.log(`worker/seed.sql written: ${seedRecipes.length} recipes`);
