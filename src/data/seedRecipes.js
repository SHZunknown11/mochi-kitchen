// Starter recipes (so the app has content before any API call). Ingredients are written as
// "measure|name;measure|name" and steps as "step|step". Diet flags and calories are NOT written by
// hand: they are computed by services/diet.js when the recipe is saved.

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function R(title, category, area, summary, servings, ingredients, steps, tags = []) {
  return {
    source: 'seed',
    externalId: slug(title),
    title,
    category,
    area,
    summary,
    servings,
    thumb: null,
    tags,
    instructions: steps.split('|').map((s) => s.trim()).join('\n'),
    ingredients: ingredients.split(';').map((pair) => {
      const [measure, name] = pair.split('|');
      return { name: name.trim(), measure: measure.trim() };
    }),
  };
}

